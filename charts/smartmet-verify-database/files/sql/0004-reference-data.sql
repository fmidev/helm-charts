-- ---------------------------------------------------------------------------
-- parameters, and the localized descriptions they hang off
-- ---------------------------------------------------------------------------
--
-- The 291 forecast parameters FMI verifies. These are reference data for the
-- same reason the estimators are, only more strongly: parameter *names* are
-- compiled into both the GUI and fmi-verification-common, where they select
-- unit conversions and axis behaviour rather than merely labelling a row.
--
--   ModelData.getValue() switches on the name and rescales TotalCloudCover and
--   TotalCloudCover2 from percent to eighths, clamps CloudBase/Ceiling at
--   5000 ft and Visibility at 10000 m. A deployment that spells cloud cover
--   differently gets values wrong by a factor of 12.5, silently.
--   ObservationManager shifts the observation window back 24 h for the name
--   Precipitation24h, and Parameter.isProbabilityParameter() divides a value by
--   100 when the name contains "probability" or equals "PoP".
--   ColumnDiagramChartBuilder, HeatMapChartBuilder, LineSeriesChartBuilder,
--   ScatterPlotChartBuilder and ModelVersusObservationsOnMapPresenter branch on
--   "Direction", "Visibility", "CloudBase", "Ceiling" and "TotalCloudCover".
--
-- Every one of those classes serves a view on the `international` whitelist, so
-- the names below are part of the contract, not a sample of FMI's catalogue.
--
-- The ids are FMI's, unchanged: RoadWeatherMenuConfig, AirportForecastMenuConfig,
-- KairosAreaMenuConfig and IndisputableIndicatorConfig hardcode parameter ids,
-- and although those views are outside the whitelist today, renumbering here
-- would make them unusable the moment a deployment enables one.
--
-- unit distinguishes NULL from the empty string on purpose. Parameter.getUnit()
-- wraps the column in an Optional, and callers such as ModelRunMonitoringChart-
-- Configuration test isPresent(), so '' renders an empty unit in parentheses
-- while NULL renders none. Both spellings are reproduced exactly as FMI has them.
--
-- No forecast data references these rows, so a deployment that verifies only a
-- handful of them is unaffected by the rest: the parameter pickers are filled
-- from the used_*_results tables, not from this table.
--
-- Insert order follows the foreign keys, as above: entries, then parameters
-- (parameters.description_id references an entry), then the translations.

-- Entry ids are offset by 100000 from the parameter id.
--
-- localization_entries is shared across tables, and the estimator block above
-- numbers its entries 1..110, equal to the estimator id. The seeded tables are
-- therefore each given a 100000-wide block of entry ids:
--
--   estimators   offset       0   ->  entry id 1 .. 110
--   parameters   offset  100000   ->  entry id 100001 .. 100865
--
-- A collision would need a seeded table to reach id 100000, five orders of
-- magnitude past where either table sits, so the blocks are disjoint by
-- construction rather than by inspection. A third table seeded here takes
-- offset 200000 and the pattern continues.
--
-- Nothing outside this file refers to an entry id -- parameters.description_id
-- is written here too -- so the renumbering away from FMI's own entry ids
-- (14040..16967, interleaved with areas, locations and producers) is safe.
