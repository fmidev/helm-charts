-- Runs on verifapi as postgres (superuser) after the production schema and the
-- ownership transfer.
--
-- Reference data the applications require in every deployment: target_types,
-- estimators and parameters, with the localized descriptions the latter two
-- hang off. These are not customer metadata: the names below are compiled into
-- the GUI, so a database without them yields a broken installation rather than
-- an empty one.
--
-- target_types: TargetTypeRadioGroup preselects GROUP, then AREA, then LOCATION,
-- and leaves the radio group unset when it finds none of them. Every query form
-- then switches on the selected name, so an empty table makes the switch throw
--   Cannot invoke "String.hashCode()" because "<local>" is null
-- on the first view the user opens. Nineteen GUI classes reach that switch, so
-- the whole interface is affected, not one view.
--
-- Idempotent on purpose. The test image (Dockerfile.test) loads the same rows
-- from csv/metadata/target_types.csv in 0003-legacy-test-data.sql, which runs
-- first; without ON CONFLICT this file would abort that build on the unique
-- name index.

INSERT INTO public.target_types (id, name)
VALUES (1, 'LOCATION'),
       (2, 'GROUP'),
       (3, 'AREA')
ON CONFLICT DO NOTHING;

-- The id column defaults to nextval() on this sequence. The rows above set ids
-- explicitly, which does not advance it, so without this a later insert that
-- omits the id would collide with id 1.
SELECT setval('public.target_types_id_seq', (SELECT max(id) FROM public.target_types));

-- ---------------------------------------------------------------------------
-- estimators, and the localized descriptions they hang off
-- ---------------------------------------------------------------------------
--
-- The 94 estimators FMI verifies with. Like target_types these are not
-- customer metadata: the GUI compiles both estimator names and estimator ids
-- into its source, so the ids below are fixed and a deployment that renumbers
-- them gets views that quietly show nothing.
--
-- Three of FMI's rows are deliberately absent: RPS (42), EPOCH (45) and
-- INDEXEPOCH (70). RPS has no implementation in the runner at all, so ordering
-- it throws and the order is still marked delivered -- a result that silently
-- never appears. EPOCH lost its only data source when the *_PERSONAL period
-- types were removed in runner 3.14.3 and has never produced a single result in
-- FMI production; INDEXEPOCH indexes exactly those never-written EPOCH rows.
-- All three are retired system-wide (fmi-verification-runner#46 and #43), and
-- no parameter_map row below offers any of them, so nothing a view can reach is
-- lost. Their ids are not reused: the gaps at 42, 45 and 70 stay gaps, so every
-- other id still means what it means at FMI.
--
-- BIAS_ON_MAP is the sharpest case. ColumnDiagramChartBuilder hardcodes id 93
-- while EstimatorComboBox looks the same row up by name, so the two agree only
-- when id 93 is the row named BIAS_ON_MAP. With the row missing altogether that
-- combo box calls findFirst() on a one-element list holding null and throws,
-- which is what made the bias-on-map view an Internal Server Error page before
-- fmi-verification-gui 3.25.1.
--
-- scale is how many decimals the GUI renders a value with, and it is NOT NULL:
-- Estimator.getScale() dereferences it unconditionally. ColorUtils derives map
-- legend limits from scale - 1, so 0 rounds those limits to tens.
--
-- character is read by the runner, not the GUI. Only SSC, SSP, SEEPS and
-- CATEGORY change behaviour; everything else takes the default branch. (The
-- EPOCH character went with estimator 45; no row carries it any more.)
--
-- Insert order is load-bearing, and follows the foreign keys:
-- localization_languages and localization_entries first, then estimators
-- (estimators.description_id references an entry), then the translations
-- (which reference both an entry and a language).

-- Language ids match FMI's so that translations synced from there later line up.
-- Swedish carries no estimator descriptions at FMI either; the row exists so the
-- id is not taken by something else.
